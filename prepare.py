#!/usr/bin/env python3
"""Prepare pinned GhostESP sources and a board-specific SDK configuration."""
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parent
LOCK = json.loads((ROOT / "upstream.json").read_text())
SOURCE = ROOT / "upstream"


def run(*args):
    return subprocess.run(args, cwd=ROOT, check=True, text=True, capture_output=True).stdout.strip()


def config_entries(text):
    result = {}
    for line in text.splitlines():
        match = re.match(r"(?:# )?(CONFIG_\w+)(?:=| is not set)", line)
        if match:
            result[match[1]] = line
    return result


def main():
    if not (SOURCE / ".git").exists():
        run("git", "clone", "--no-checkout", LOCK["repository"], str(SOURCE))
        run("git", "-C", str(SOURCE), "checkout", "--detach", LOCK["revision"])
    revision = run("git", "-C", str(SOURCE), "rev-parse", "HEAD")
    if revision != LOCK["revision"]:
        raise SystemExit(f"Upstream revision mismatch: {revision}; expected {LOCK['revision']}")
    patch = ROOT / "board.patch"
    if patch.exists():
        reverse = subprocess.run(["git", "-C", str(SOURCE), "apply", "--reverse", "--check", str(patch)], capture_output=True)
        if reverse.returncode != 0:
            run("git", "-C", str(SOURCE), "apply", "--check", str(patch))
            run("git", "-C", str(SOURCE), "apply", str(patch))
    config = config_entries((SOURCE / "configs/sdkconfig.default.esp32c3").read_text())
    # Keep the upstream C3 radio/memory settings and use the round board's
    # LVGL feature selections. The final overlay supplies this board's pins.
    gui = config_entries((SOURCE / "configs/sdkconfig.crowpanel_1p28_rotary").read_text())
    config.update({k: v for k, v in gui.items() if k.startswith("CONFIG_LV_")})
    config.update(config_entries((ROOT / "sdkconfig.board").read_text()))
    # Old console aliases in the C3 preset otherwise override the modern
    # ESP_CONSOLE_* choice when IDF migrates sdkconfig.
    config = {k: v for k, v in config.items() if not k.startswith("CONFIG_CONSOLE_")}
    # The C3 preset also contains an old TX-buffer alias. IDF migration would
    # silently restore sixteen buffers over the board's modern setting.
    config.pop("CONFIG_ESP32_WIFI_STATIC_TX_BUFFER_NUM", None)
    # IDF migration of these old aliases otherwise restores verbose assertions.
    config = {k: v for k, v in config.items()
              if not k.startswith("CONFIG_OPTIMIZATION_ASSERTION")}
    build = ROOT / "build"
    build.mkdir(exist_ok=True)
    defaults = build / "sdkconfig.defaults"
    content = "# Generated by prepare.py\n" + "\n".join(config.values()) + "\n"
    changed = not defaults.exists() or defaults.read_text() != content
    defaults.write_text(content)
    if changed or not (build / "sdkconfig").exists():
        (build / "sdkconfig").write_text(content)
    dependency_lock = ROOT / "dependencies.lock"
    if dependency_lock.exists():
        (SOURCE / "dependencies.lock").write_bytes(dependency_lock.read_bytes())
    print(f"Prepared GhostESP {revision[:12]} for ESP32-2424S012")


if __name__ == "__main__":
    main()
